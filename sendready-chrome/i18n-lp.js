// <html data-lp-lang> で言語が決まっており、本文も生成済み。実行時に訳し直さない
// （クローラが英語ブラウザ扱いで描画しても、その言語の本文のまま索引させるため）。
function fixedLPLocale() {
  var l = document.documentElement.getAttribute("data-lp-lang");
  return l && LP_MESSAGES[l] ? l : null;
}

// 言語 → その言語の LP の URL（en はルート）。data-lp-base は LP ルートへの相対パス
function lpPageURL(locale) {
  var base = document.documentElement.getAttribute("data-lp-base");
  return base + (locale === "en" ? "" : locale + "/");
}

// 言語タグ（?lang= の値・ブラウザ言語。拡張は繁体字を zh_TW で渡す）→ LP の言語。対応外は null
function matchLPLocale(tag) {
  const supported = Object.keys(LP_MESSAGES);
  const t = String(tag || "").toLowerCase().replace(/_/g, "-");
  if (!t) return null;
  if (/^zh-(tw|hk|mo|hant)/.test(t)) return supported.includes("zh-TW") ? "zh-TW" : "zh";
  const exact = supported.find(function (s) { return s.toLowerCase() === t; });
  if (exact) return exact;
  const primary = t.split("-")[0];
  return supported.includes(primary) ? primary : null;
}

function detectLPLocale() {
  const fixed = fixedLPLocale();
  if (fixed) return fixed;
  // URL の ?lang=xx を最優先(拡張機能がアプリの言語を引き継いで開くため)
  const q = (function(){ try { return new URLSearchParams(location.search).get("lang") || ""; } catch (e) { return ""; } })();
  const saved = (function(){ try { return localStorage.getItem("lp_lang"); } catch (e) { return null; } })();
  return matchLPLocale(q) || (saved && LP_MESSAGES[saved] ? saved : null) ||
    matchLPLocale(navigator.language || navigator.userLanguage) || "en";
}

// ── Apply Translations ──────────────────────────────────────────────
function applyLPTranslations(locale) {
  const msgs = LP_MESSAGES[locale] || LP_MESSAGES.en;
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    const key = el.getAttribute("data-i18n");
    if (msgs[key] !== undefined) el.textContent = msgs[key];
  });
  document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
    const key = el.getAttribute("data-i18n-html");
    if (msgs[key] !== undefined) el.innerHTML = msgs[key];
  });
  document.documentElement.lang = locale;
  document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";

  // swap the promo video to the matching language
  var vid = LP_VIDEO_IDS[locale] || LP_VIDEO_IDS.en;
  var vf = document.getElementById("promo-video");
  if (vf && vid) {
    var src = "https://www.youtube.com/embed/" + vid;
    if (vf.getAttribute("src") !== src) vf.setAttribute("src", src);
  }

  // ウェブストアへのリンクに表示言語を付ける（ストアの流入元で LP の言語別に見分ける）
  document.querySelectorAll('a[href*="chromewebstore.google.com/detail/"]').forEach(function (a) {
    try {
      var u = new URL(a.href);
      u.searchParams.set("utm_campaign", locale);
      a.href = u.toString();
    } catch (e) {}
  });
}

// ── Init ────────────────────────────────────────────────────────────
function initLP() {
  var locale = detectLPLocale();
  if (!fixedLPLocale()) applyLPTranslations(locale);

  var selector = document.getElementById("lang-select");
  if (selector) {
    // populate options in registry order
    var order = Object.keys(LP_MESSAGES);
    selector.innerHTML = order.map(function (code) {
      return '<option value="' + code + '">' + (LP_LANG_NAMES[code] || code) + "</option>";
    }).join("");
    selector.value = locale;
    selector.addEventListener("change", function () {
      var newLocale = this.value;
      try { localStorage.setItem("lp_lang", newLocale); } catch (e) {}
      // LP は言語ごとに URL を持つので、その言語のページへ移る（使い方ページはその場で切替）
      if (document.documentElement.hasAttribute("data-lp-base")) {
        location.href = lpPageURL(newLocale);
        return;
      }
      applyLPTranslations(newLocale);
      this.value = newLocale;
    });
  }
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initLP);
} else {
  initLP();
}

// ── Language names (for the selector) ───────────────────────────────
const LP_LANG_NAMES = {
  en: "English", ja: "日本語", zh: "中文", ko: "한국어", es: "Español",
  fr: "Français", de: "Deutsch", pt: "Português", hi: "हिन्दी", id: "Indonesia", ar: "العربية"
};

// ── Detect Locale ───────────────────────────────────────────────────
function detectLPLocale() {
  const supported = Object.keys(LP_MESSAGES);
  // URL の ?lang=xx を最優先(拡張機能がアプリの言語を引き継いで開くため)
  const q = (function(){ try { return (new URLSearchParams(location.search).get("lang") || "").toLowerCase(); } catch (e) { return ""; } })();
  if (q && supported.includes(q)) return q;
  const saved = (function(){ try { return localStorage.getItem("lp_lang"); } catch (e) { return null; } })();
  if (saved && supported.includes(saved)) return saved;
  const nav = (navigator.language || navigator.userLanguage || "en").toLowerCase();
  if (supported.includes(nav)) return nav;
  const primary = nav.split("-")[0];
  if (supported.includes(primary)) return primary;
  return "en";
}

// ── Apply Translations ──────────────────────────────────────────────
function applyLPTranslations(locale) {
  const msgs = LP_MESSAGES[locale] || LP_MESSAGES.en;
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    const key = el.getAttribute("data-i18n");
    if (msgs[key] !== undefined) el.textContent = msgs[key];
  });
  document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
    const key = el.getAttribute("data-i18n-html");
    if (msgs[key] !== undefined) el.innerHTML = msgs[key];
  });
  document.documentElement.lang = locale;
  document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
}

// ── Init ────────────────────────────────────────────────────────────
function initLP() {
  var locale = detectLPLocale();
  applyLPTranslations(locale);

  var selector = document.getElementById("lang-select");
  if (selector) {
    // populate options in registry order
    var order = Object.keys(LP_MESSAGES);
    selector.innerHTML = order.map(function (code) {
      return '<option value="' + code + '">' + (LP_LANG_NAMES[code] || code) + "</option>";
    }).join("");
    selector.value = locale;
    selector.addEventListener("change", function () {
      var newLocale = this.value;
      try { localStorage.setItem("lp_lang", newLocale); } catch (e) {}
      applyLPTranslations(newLocale);
      this.value = newLocale;
    });
  }
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initLP);
} else {
  initLP();
}

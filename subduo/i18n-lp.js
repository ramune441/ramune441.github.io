// ── Language names (for the selector) ───────────────────────────────
var LP_LANG_NAMES = {
  en: "English", ja: "日本語", zh: "简体中文", "zh-TW": "繁體中文", ko: "한국어", es: "Español",
  fr: "Français", de: "Deutsch", it: "Italiano", pt: "Português", ru: "Русский", hi: "हिन्दी"
};

// ── Detect locale ───────────────────────────────────────────────────
function normalizeLPLocale(raw) {
  var s = String(raw || "").toLowerCase();
  if (!s) return "";
  if (/^zh(-|$)/.test(s)) {
    return /^zh-(tw|hk|mo|hant)/.test(s) ? "zh-TW" : "zh";
  }
  var primary = s.split("-")[0];
  return LP_MESSAGES[primary] ? primary : "";
}
function detectLPLocale() {
  var q = "";
  try { q = new URLSearchParams(location.search).get("lang") || ""; } catch (e) {}
  var fromQuery = normalizeLPLocale(q);
  if (fromQuery) return fromQuery;
  var saved = null;
  try { saved = localStorage.getItem("lp_lang"); } catch (e) {}
  if (saved && LP_MESSAGES[saved]) return saved;
  var nav = normalizeLPLocale(navigator.language || navigator.userLanguage || "en");
  return nav || "en";
}

// ── Apply translations ──────────────────────────────────────────────
function applyLPTranslations(locale) {
  var msgs = LP_MESSAGES[locale] || LP_MESSAGES.en;
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    var key = el.getAttribute("data-i18n");
    if (msgs[key] !== undefined) el.textContent = msgs[key];
  });
  document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
    var key = el.getAttribute("data-i18n-html");
    if (msgs[key] !== undefined) el.innerHTML = msgs[key];
  });
  document.documentElement.lang = locale;
  document.documentElement.dir = "ltr";
  document.dispatchEvent(new CustomEvent("lp:lang", { detail: { locale: locale } }));
}

// ── Init ────────────────────────────────────────────────────────────
function initLP() {
  var locale = detectLPLocale();
  applyLPTranslations(locale);

  var selector = document.getElementById("lang-select");
  if (selector) {
    selector.innerHTML = Object.keys(LP_MESSAGES).map(function (code) {
      return '<option value="' + code + '">' + (LP_LANG_NAMES[code] || code) + "</option>";
    }).join("");
    selector.value = locale;
    selector.addEventListener("change", function () {
      var next = this.value;
      try { localStorage.setItem("lp_lang", next); } catch (e) {}
      applyLPTranslations(next);
      this.value = next;
    });
  }
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initLP);
} else {
  initLP();
}

// Pulls the app's own strings (app/src/main/res/values*/strings.xml in the Kura repo) into
// store-images-app-strings.js, so the screens in the store images say exactly what the app says.
// Run again whenever the app's strings change: node store-images-strings.mjs [path/to/Kura]
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
// The repo sits next to this one; its folder is being renamed from PhotoDeclutter to Kura.
const repo = [process.argv[2], '../../Kura', '../../PhotoDeclutter']
  .filter(Boolean).map(p => path.resolve(here, p))
  .find(p => fs.existsSync(path.join(p, 'app/src/main/res/values/strings.xml')));
if (!repo) throw new Error('Kura repo not found; pass its path as the first argument');
const res = path.join(repo, 'app/src/main/res');

// Keys are the folder names of images/store/<lang>.
const DIRS = {
  en: 'values', ja: 'values-ja', zh: 'values-b+zh+Hans', 'zh-TW': 'values-b+zh+Hant', ko: 'values-ko',
  es: 'values-es', fr: 'values-fr', de: 'values-de', pt: 'values-pt', it: 'values-it', ru: 'values-ru', id: 'values-in',
  hi: 'values-hi', tr: 'values-tr', vi: 'values-vi', th: 'values-th', pl: 'values-pl', ar: 'values-ar',
};

const unescape = s => s
  .replace(/^"(.*)"$/s, '$1')
  .replace(/\\'/g, "'").replace(/\\"/g, '"').replace(/\\n/g, '\n').replace(/\\@/g, '@').replace(/\\\?/g, '?')
  .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');

const out = {};
for (const [lang, dir] of Object.entries(DIRS)) {
  const xml = fs.readFileSync(path.join(res, dir, 'strings.xml'), 'utf8').replace(/<!--[\s\S]*?-->/g, '');
  const t = {};
  for (const m of xml.matchAll(/<string name="([^"]+)"[^>]*>([\s\S]*?)<\/string>/g)) t[m[1]] = unescape(m[2].trim());
  for (const m of xml.matchAll(/<plurals name="([^"]+)"[^>]*>([\s\S]*?)<\/plurals>/g)) {
    const forms = {};
    for (const q of m[2].matchAll(/<item quantity="([^"]+)">([\s\S]*?)<\/item>/g)) forms[q[1]] = unescape(q[2].trim());
    t[m[1]] = forms;
  }
  out[lang] = t;
}
fs.writeFileSync(path.join(here, 'store-images-app-strings.js'),
  '// Generated by store-images-strings.mjs from the Kura app\'s strings.xml. Do not edit by hand.\n' +
  'window.APP_STRINGS = ' + JSON.stringify(out, null, 1) + ';\n');
console.log(repo + ' → ' + Object.entries(out).map(([l, t]) => `${l}: ${Object.keys(t).length}`).join(', '));

// ── Locale Detection ────────────────────────────────────────────────
function detectLPLocale() {
  const supported = Object.keys(LP_MESSAGES);

  // ?lang=xx overrides browser-language detection (verification / sharing)
  try {
    const forced = new URLSearchParams(location.search).get("lang");
    if (forced && supported.includes(forced.toLowerCase())) return forced.toLowerCase();
  } catch (e) {}

  const nav = (navigator.language || navigator.userLanguage || "en").toLowerCase();

  // Exact match first (e.g. "en", "ja", "zh")
  if (supported.includes(nav)) return nav;

  // Match primary subtag (e.g. "en-US" -> "en", "zh-CN" -> "zh", "pt-BR" -> "pt")
  const primary = nav.split("-")[0];
  if (supported.includes(primary)) return primary;

  // Default to English
  return "en";
}

// ── Apply Translations ──────────────────────────────────────────────
// {ui:key} in a message = the extension's own label in that language, from
// guide-ui.js (generated from the extension's i18n.js by guide-shots.js), so
// the usage guide always names buttons exactly as the popup shows them.
function fillUILabels(text, locale) {
  if (typeof GUIDE_UI === "undefined" || text.indexOf("{ui:") === -1) return text;
  var ui = GUIDE_UI[locale] || GUIDE_UI.en;
  return text.replace(/\{ui:(\w+)\}/g, function (m, key) {
    return ui[key] !== undefined ? ui[key] : m;
  });
}

function escapeLPHtml(text) {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function applyLPTranslations(locale) {
  const msgs = LP_MESSAGES[locale] || LP_MESSAGES.en;

  // Handle data-i18n (textContent)
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    const key = el.getAttribute("data-i18n");
    if (msgs[key] !== undefined) {
      el.textContent = fillUILabels(msgs[key], locale);
    }
  });

  // Handle data-i18n-html (innerHTML) — for keys containing HTML markup.
  // UI labels are plain text, so they are escaped before insertion.
  document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
    const key = el.getAttribute("data-i18n-html");
    if (msgs[key] !== undefined) {
      el.innerHTML = msgs[key].split(/(\{ui:\w+\})/).map(function (part) {
        return /^\{ui:\w+\}$/.test(part) ? escapeLPHtml(fillUILabels(part, locale)) : part;
      }).join("");
    }
  });

  // swap the popup screenshots (usage guide page) to the matching language
  document.querySelectorAll("img[data-guide-shot]").forEach(function (img) {
    var src = "guide-shots/" + locale + "/" + img.getAttribute("data-guide-shot") + ".webp";
    if (img.getAttribute("src") !== src) img.setAttribute("src", src);
  });

  // Handle data-i18n-ph (placeholder attribute) — for form inputs
  document.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
    const key = el.getAttribute("data-i18n-ph");
    if (msgs[key] !== undefined) {
      el.setAttribute("placeholder", msgs[key]);
    }
  });

  // Set document lang attribute
  document.documentElement.lang = locale;

  // Set dir attribute for RTL languages
  document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";

  // swap the promo video to the matching language
  var vid = LP_VIDEO_IDS[locale] || LP_VIDEO_IDS.en;
  var vf = document.getElementById("promo-video");
  if (vf && vid) {
    var src = "https://www.youtube.com/embed/" + vid;
    if (vf.getAttribute("src") !== src) vf.setAttribute("src", src);
  }

  // swap the guide demo video (usage guide page) to the matching language
  var gv = document.getElementById("guide-demo-video");
  if (gv) {
    var gsrc = "guide-demo-" + locale + ".mp4";
    if (gv.getAttribute("src") !== gsrc) {
      gv.muted = true;
      gv.setAttribute("poster", "guide-demo-" + locale + "-poster.jpg");
      gv.setAttribute("src", gsrc);
      gv.load();
      if (gv.play) gv.play().catch(function () {});
    }
  }
}


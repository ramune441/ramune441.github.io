// chrome.* stub for popup.js: storage backed by `store`, a single active tab,
// background reporting no job in progress
function installChromeStub(page, store) {
  return page.evaluateOnNewDocument((storeJson, tabUrl) => {
    const data = JSON.parse(storeJson);
    const clone = v => (v === undefined ? v : JSON.parse(JSON.stringify(v)));
    const pick = keys => {
      if (keys == null) return clone(data);
      if (typeof keys === 'string') keys = [keys];
      const out = {};
      if (Array.isArray(keys)) { for (const k of keys) if (k in data) out[k] = clone(data[k]); }
      else { for (const k of Object.keys(keys)) out[k] = k in data ? clone(data[k]) : keys[k]; }
      return out;
    };
    const done = (val, cb) => { if (typeof cb === 'function') setTimeout(() => cb(val)); return Promise.resolve(val); };
    const noopEvent = { addListener() {}, removeListener() {} };
    const chromeStub = {
      storage: {
        local: {
          get: (keys, cb) => done(pick(keys), cb),
          set: (obj, cb) => { Object.assign(data, clone(obj)); return done(undefined, cb); },
          remove: (keys, cb) => { for (const k of [].concat(keys)) delete data[k]; return done(undefined, cb); },
        },
        onChanged: noopEvent,
      },
      runtime: { sendMessage: () => Promise.resolve({ state: 'idle' }), onMessage: noopEvent, getURL: p => p },
      tabs: {
        query: () => Promise.resolve([{ id: 1, url: tabUrl, active: true }]),
        sendMessage: () => Promise.resolve({}),
        create: () => Promise.resolve({}),
      },
    };
    Object.defineProperty(window, 'chrome', { value: chromeStub, configurable: true, writable: true });
  }, JSON.stringify(store), TAB_URL);
}

async function openPopup(browser, lang, store) {
  const page = await browser.newPage();
  await page.setViewport({ width: POPUP_W, height: POPUP_H, deviceScaleFactor: 2 });
  const cdp = await page.createCDPSession();
  await cdp.send('Emulation.setLocaleOverride', { locale: BCP47[lang] || lang });
  await installChromeStub(page, store);
  const url = 'file:///' + path.join(EXT_DIR, 'popup.html').replace(/\\/g, '/');
  await page.goto(url, { waitUntil: 'load' });
  // popup.js init has run once the profiles, saved inputs and review bubble are in
  await page.waitForFunction(() =>
    document.querySelectorAll('#run-preset-select option').length > 0 &&
    document.querySelector('#site-history-list').children.length > 0 &&
    document.querySelector('#review-gate .rg-bubble'), { timeout: 10000 });
  return page;
}

// Grow the viewport until no scroll container is clipped, so the whole
// popup content is visible (the real popup scrolls instead)
async function expandToContent(page) {
  await page.addStyleTag({ content: 'body { height: 100vh !important; }' });
  let height = POPUP_H;
  for (let i = 0; i < 6; i++) {
    const extra = await page.evaluate(() =>
      [...document.querySelectorAll('.profile-body, .fill-action, .tab-content')]
        .filter(el => el.offsetParent !== null)
        .reduce((sum, el) => sum + Math.max(0, el.scrollHeight - el.clientHeight), 0));
    if (extra <= 0) break;
    height += extra;
    await page.setViewport({ width: POPUP_W, height, deviceScaleFactor: 2 });
  }
  return height;
}

// Red numbered badges (same look as the guide's .desc-num), centred on the
// target's left/right edge, its top-right corner ('corner'), just under it
// ('below'), or just past the end of a text ('after'); left/right/corner/after
// mirror in RTL
async function addBadges(page, specs, rtl) {
  await page.evaluate((specs, rtl) => {
    const st = document.createElement('style');
    st.textContent = '.gs-badge{position:absolute;z-index:2147483647;width:20px;height:20px;border-radius:50%;' +
      'background:#ef4444;color:#fff;font:700 11px/20px "Segoe UI",Arial,sans-serif;text-align:center;' +
      'box-shadow:0 0 0 2px #fff,0 2px 5px rgba(0,0,0,.3);pointer-events:none;direction:ltr}';
    document.head.appendChild(st);
    const R = 10;
    for (const { sel, n, side } of specs) {
      const el = document.querySelector(sel);
      if (!el) throw new Error('badge target not found: ' + sel);
      const r = el.getBoundingClientRect();
      const s = rtl && side === 'left' ? 'right' : rtl && side === 'right' ? 'left' : side;
      const atEnd = s === 'right' || (s === 'corner' && !rtl);
      const atStart = s === 'left' || (s === 'corner' && rtl);
      let cx = atStart ? r.left : atEnd ? r.right : r.left + r.width / 2;
      if (s === 'after') cx = rtl ? r.left - R - 4 : r.right + R + 4;
      let cy = s === 'corner' ? r.top : s === 'below' ? r.bottom + R + 3 : r.top + r.height / 2;
      cx = Math.max(R + 2, Math.min(window.innerWidth - R - 2, cx));
      cy = Math.max(R + 2, cy);
      const b = document.createElement('div');
      b.className = 'gs-badge';
      b.textContent = n;
      b.style.left = (cx - R) + 'px';
      b.style.top = (cy - R) + 'px';
      document.body.appendChild(b);
    }
  }, specs, rtl);
}

async function shoot(page, file, clip) {
  await page.evaluate(() => document.activeElement && document.activeElement.blur && document.activeElement.blur());
  await page.screenshot({ path: file, type: 'webp', quality: 90, ...(clip ? { clip } : {}) });
}


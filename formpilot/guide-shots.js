// ── Extension strings ────────────────────────────────────────────────
function loadExtensionStrings() {
  const src = fs.readFileSync(path.join(EXT_DIR, 'i18n.js'), 'utf8');
  const ctx = vm.createContext({});
  vm.runInContext(src + '\n;globalThis.__messages = messages;', ctx);
  const messages = ctx.__messages;
  for (const lang of ALL_LANGS) {
    const dir = LOCALE_DIRS[lang] || lang;
    const loc = JSON.parse(fs.readFileSync(path.join(EXT_DIR, '_locales', dir, 'messages.json'), 'utf8'));
    messages[lang].appName = loc.appName.message;
  }
  return messages;
}

// The extension's t(): fall back to English, fill {0}, {1}, ...
function makeT(messages, lang) {
  return (key, ...a) => {
    let s = messages[lang][key] ?? messages.en[key];
    if (s === undefined) throw new Error(`i18n.js has no "${key}"`);
    a.forEach((v, i) => { s = s.replace(`{${i}}`, v); });
    return s;
  };
}

// ── 1. guide-ui.js ───────────────────────────────────────────────────
function writeGuideUI(messages) {
  const keys = Object.keys(messages.en).sort();
  const table = {};
  for (const lang of ALL_LANGS) {
    table[lang] = {};
    for (const k of keys) {
      const v = messages[lang][k];
      if (v === undefined) throw new Error(`i18n-lp.js uses {ui:${k}} but the extension has no "${k}" for ${lang}`);
      table[lang][k] = v;
    }
  }
  const body = ALL_LANGS.map(l => `${l}: ${JSON.stringify(table[l])}`).join(',\n');
  fs.writeFileSync(path.join(__dirname, 'guide-ui.js'),
    '// Generated by guide-shots.js from the FormPilot extension (i18n.js, _locales).\n' +
    '// Labels that texts in i18n-lp.js reference as {ui:key}. Do not edit by hand.\n' +
    `const GUIDE_UI = {\n${body}\n};\n`);
  console.log(`guide-ui.js: ${keys.length} labels x ${ALL_LANGS.length} languages`);
  return table;
}

// ── 2. guide-demo.html ui-strings block ──────────────────────────────
function syncDemoStrings(messages) {
  const file = path.join(__dirname, 'guide-demo.html');
  const html = fs.readFileSync(file, 'utf8');
  const ui = {};
  for (const lang of ALL_LANGS) {
    ui[lang] = {};
    for (const k of DEMO_UI_KEYS) ui[lang][k] = messages[lang][k] ?? messages.en[k];
  }
  const block = `/* ui-strings:start */\nconst UI = {\n${ALL_LANGS.map(l => `${l}: ${JSON.stringify(ui[l])}`).join(',\n')}\n};\n/* ui-strings:end */`;
  const re = /\/\* ui-strings:start \*\/[\s\S]*?\/\* ui-strings:end \*\//;
  if (!re.test(html)) throw new Error('guide-demo.html: ui-strings markers not found');
  const eol = html.includes('\r\n') ? '\r\n' : '\n';
  fs.writeFileSync(file, html.replace(re, block.replace(/\n/g, eol)));
  console.log('guide-demo.html: menu/toast strings synced');
}

